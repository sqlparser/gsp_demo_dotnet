SELECT TOP 10
    app.REFSTR
    ,app.NAME
    ,app.VERSION
    ,STRING_AGG(ISNULL(bcap.LEVELID+' '+bcap.NAME,'')+bcap.NAME,CHAR(10)) WITHIN GROUP (ORDER BY LEVELIDNUM)
FROM APPLICATION app
    JOIN RELATIONS r ON r.TOREF=app.REFSTR
    JOIN DOMAIN bcap ON bcap.REFSTR=r.FROMREF
GROUP BY app.REFSTR,app.NAME,app.VERSION
ORDER BY app.NAME